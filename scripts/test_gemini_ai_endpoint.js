// Full end-to-end test script for Growth OS AI Services
const path = require("path");
require("dotenv").config({ path: path.resolve(__dirname, "../.env") });

async function run() {
  console.log("=== Growth OS Gemini AI Live Verification Suite ===");
  const keyPresent = Boolean(process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY);
  console.log("GEMINI_API_KEY loaded:", keyPresent ? "YES (Configured)" : "NO");

  if (!keyPresent) {
    console.error("FATAL: GEMINI_API_KEY is not loaded in .env");
    process.exit(1);
  }

  const {
    generateAiReviewReply,
    generateAiPost,
    generateCopilotAnswer,
    generateAiDescription
  } = await import("../src/lib/growth_os/aiService.js");

  const business = {
    name: "SM NextGen Consulting",
    category: "Digital Growth & Local SEO Agency",
    city: "Udaipur",
    address: "101 High Street, Udaipur, Rajasthan",
    phone: "+91 70735 38077",
    website: "https://www.smnextgen.com",
    services: ["Google Business Profile Optimization", "Local 3-Pack SEO", "AI Automation"]
  };

  // 1. Test Review Reply
  console.log("\n[1/4] Testing AI Review Reply Generator...");
  const t0 = Date.now();
  const reviewRes = await generateAiReviewReply({
    review: {
      author: "Priya Sharma",
      rating: 5,
      text: "Outstanding service! They optimized our Google profile and we saw a 40% increase in calls within 3 weeks."
    },
    business,
    tone: "professional"
  });
  console.log(`Reply generated in ${Date.now() - t0}ms:`);
  console.log(`Model: ${reviewRes.model} | Source: ${reviewRes.source} | isLiveAi: ${reviewRes.isLiveAi}`);
  console.log(`Reply content: "${reviewRes.reply}"`);

  if (!reviewRes.isLiveAi || reviewRes.source !== "gemini-ai") {
    throw new Error("Review reply was not generated by live Gemini AI!");
  }

  // 2. Test Google Post Generator
  console.log("\n[2/4] Testing AI Google Post Generator...");
  const t1 = Date.now();
  const postRes = await generateAiPost({
    business,
    topic: "Pre-Festive Local Search Audit Special",
    offerType: "Limited Offer",
    ctaType: "Book Now"
  });
  console.log(`Post generated in ${Date.now() - t1}ms:`);
  console.log(`Title: "${postRes.title}"`);
  console.log(`Content preview: "${postRes.content.slice(0, 120)}..."`);
  console.log(`CTA: ${postRes.suggestedCta} | isLiveAi: ${postRes.isLiveAi}`);

  if (!postRes.isLiveAi || postRes.source !== "gemini-ai") {
    throw new Error("Post was not generated by live Gemini AI!");
  }

  // 3. Test Copilot Chat
  console.log("\n[3/4] Testing AI Growth Copilot Chat...");
  const t2 = Date.now();
  const copilotRes = await generateCopilotAnswer({
    query: "How can I rank #1 in the Google Maps 3-Pack for digital marketing in Udaipur?",
    business,
    auditScore: 78
  });
  console.log(`Copilot answered in ${Date.now() - t2}ms:`);
  console.log(`Answer preview: "${copilotRes.reply.slice(0, 150)}..."`);
  console.log(`Model: ${copilotRes.model} | isLiveAi: ${copilotRes.isLiveAi}`);

  if (!copilotRes.isLiveAi || copilotRes.source !== "gemini-ai") {
    throw new Error("Copilot chat was not answered by live Gemini AI!");
  }

  // 4. Test GBP Description
  console.log("\n[4/4] Testing 750-Char GBP Description Generator...");
  const t3 = Date.now();
  const descRes = await generateAiDescription({
    business,
    keywords: "local SEO, Google Business Profile management, Udaipur agency"
  });
  console.log(`Description generated in ${Date.now() - t3}ms (Length: ${descRes.description.length} chars):`);
  console.log(`Description: "${descRes.description}"`);
  console.log(`Model: ${descRes.model} | isLiveAi: ${descRes.isLiveAi}`);

  if (!descRes.isLiveAi || descRes.source !== "gemini-ai") {
    throw new Error("Description was not generated by live Gemini AI!");
  }

  console.log("\n========================================================");
  console.log(">>> ALL 4 GROWTH OS GEMINI AI TOOLS VERIFIED LIVE & WORKING! <<<");
  console.log("========================================================");
}

run().catch(err => {
  console.error("Verification failed:", err);
  process.exit(1);
});
