// Verify Growth OS Live on Vercel (https://www.smnextgen.com)
const path = require("path");
require("dotenv").config({ path: path.resolve(__dirname, "../.env") });
const { Client } = require("pg");

const LIVE_BASE = "https://www.smnextgen.com";

async function verifyLive() {
  console.log("=== Growth OS Live Production Verification (smnextgen.com) ===");
  const t0 = Date.now();

  // Step 1: Health check / me endpoint
  console.log("\n[1/5] Checking Public Health on Live Domain...");
  const meRes = await fetch(`${LIVE_BASE}/api/growth-os/auth/me`);
  console.log(`GET /api/growth-os/auth/me => HTTP ${meRes.status}`);
  if (!meRes.ok) {
    console.error("Failed to reach /api/growth-os/auth/me");
    return false;
  }

  // Step 2: Register a fresh user on smnextgen.com
  console.log("\n[2/5] Testing Account Registration on smnextgen.com...");
  const stamp = Date.now();
  const testEmail = `live_owner_${stamp}@smnextgen.com`;
  const regRes = await fetch(`${LIVE_BASE}/api/growth-os/auth/register`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      name: "Live Cloud Owner",
      email: testEmail,
      password: "CloudPassword2026!"
    })
  });

  const regData = await regRes.json();
  console.log(`POST /api/growth-os/auth/register => HTTP ${regRes.status}:`, regData);

  if (regRes.status === 500) {
    console.log("Still deploying or environment variables are still being propagated by Vercel.");
    return false;
  }

  if (!regRes.ok || !regData.success) {
    throw new Error(`Registration failed: ${JSON.stringify(regData)}`);
  }

  const cookie = regRes.headers.get("set-cookie");
  console.log("Session Cookie received:", Boolean(cookie));

  // Step 3: Verify user was directly persisted to Supabase Cloud PostgreSQL
  console.log("\n[3/5] Verifying Direct Persistence in Cloud Supabase PostgreSQL...");
  const client = new Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();
  const dbUser = await client.query("SELECT id, email, name, role FROM users WHERE email = $1", [testEmail]);
  if (dbUser.rows.length === 0) {
    await client.end();
    throw new Error("User registered on Vercel was NOT found in Supabase Database!");
  }
  console.log("Found in Cloud Supabase DB:", dbUser.rows[0]);
  await client.end();

  // Step 4: Complete Onboarding Profile on smnextgen.com
  console.log("\n[4/5] Testing Business Profile Onboarding on smnextgen.com...");
  const bizRes = await fetch(`${LIVE_BASE}/api/growth-os/business`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Cookie": cookie
    },
    body: JSON.stringify({
      name: "Udaipur Royal Boutique",
      category: "Fashion & Lifestyle Retail",
      country: "India",
      city: "Udaipur",
      address: "Fateh Sagar Road, Udaipur",
      phone: "+91 98290 55555",
      website: "https://royalboutique.in",
      services: ["Designer Ethnic Wear", "Custom Bridal Tailoring", "Handloom Silks"]
    })
  });
  const bizData = await bizRes.json();
  console.log(`POST /api/growth-os/business => HTTP ${bizRes.status}:`, bizData.success ? "Success" : bizData);
  if (!bizRes.ok) {
    throw new Error(`Business creation failed: ${JSON.stringify(bizData)}`);
  }

  // Step 5: Test Live Gemini AI Generation via smnextgen.com
  console.log("\n[5/5] Testing Live Gemini AI Generation on smnextgen.com...");
  const aiRes = await fetch(`${LIVE_BASE}/api/growth-os/ai`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Cookie": cookie
    },
    body: JSON.stringify({
      action: "copilot_chat",
      message: "What are 2 immediate marketing tactics for our boutique near Fateh Sagar?",
      score: 75
    })
  });
  const aiData = await aiRes.json();
  console.log(`POST /api/growth-os/ai => HTTP ${aiRes.status}`);
  console.log("isLiveAi:", aiData.isLiveAi);
  console.log("source:", aiData.source);
  console.log("model:", aiData.model);
  console.log("AI Copilot Response:\n", aiData.reply);

  if (!aiData.isLiveAi || aiData.source !== "gemini-ai") {
    throw new Error("AI response was not generated by live Gemini AI on smnextgen.com!");
  }

  console.log("\n========================================================");
  console.log(`>>> GROWTH OS IS 100% LIVE & FUNCTIONAL ON SMNEXTGEN.COM! <<< (Total time: ${Date.now() - t0}ms)`);
  console.log("========================================================");
  return true;
}

verifyLive().catch(err => {
  console.error("Live verification error:", err.message);
  process.exit(1);
});
